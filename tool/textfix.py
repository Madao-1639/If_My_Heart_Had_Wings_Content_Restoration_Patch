TRAIL_SPACE = re.compile(r'[ \t]+(?=[」』”’）)。，、]*[ \t]*(?:%[KP])*[ \t]*$)')


def strip_notes(cn):
    for lit in WORK_NOTE_LITERAL:
        cn = cn.replace(lit, '')
    cn = WORK_NOTE.sub('', cn)
    cn = WORK_NOTE_PAREN.sub('', cn)
    cn = WORK_NOTE_STAR.sub('', cn)
    return cn


def strip_ruby(cn):
    return RUBY.sub(lambda m: m.group(1), cn)


def normalize(cn):
    """按固定顺序执行全部零判断改写，返回规范化后的译文。"""
    if cn is None:
        return cn
    s = strip_notes(cn)
    s = strip_ruby(s)
    s = GLOSS_KANA.sub('', s)
    for old, new in TERM_FIX:
        if old in s:
            s = s.replace(old, new)
    for rx, new in TERM_FIX_RE:
        s = rx.sub(new, s)
    s = to_simplified(s)
    for rx, new in ZHU_RESTORE:
        s = rx.sub(new, s)
    s = ITER_MARK.sub(lambda m: m.group(1) + m.group(1), s)
    for ch, new in GLYPH_MAP.items():
        if ch in s:
            s = s.replace(ch, new)
    s = TITLE_FEMALE.sub(r'\1学姐', s)
    s = TITLE_MALE.sub(r'\1学长', s)
    s = ''.join(PUNCT_MAP.get(c, c) for c in s)
    s = ''.join(ASCII_PUNCT.get(c, c) for c in s)
    s = DOT_ELLIPSIS.sub('……', s)
    s = FULLWIDTH_ALNUM.sub(lambda m: unicodedata.normalize('NFKC', m.group(0)), s)
    s = FULLWIDTH_PCT.sub('%', s)
    s = DIGIT_DOT.sub('.', s)
    s = LATIN_UNIT_M.sub('米', s)
    # 用 lambda 做替换体：字符串形式的 '\\n　' 会被 re 还原成真实换行
    s = SOFT_INDENT.sub(lambda m: '\\n　', s)
    s = ASCII_COMMA.sub('，', s)
    s = YEN_UNIT.sub('日元', s)
    s = YEN_WORD.sub('日元', s)
    for rx, new in DUP_PUNCT:
        s = rx.sub(new, s)
    s = BIAN_DE.sub('变得', s)
    s = ORPHAN_MORA.sub('', s)
    s = ORPHAN_KANA.sub('', s)
    # 批注剥除后残留的空引号/空括号对与尾随空格
    s = re.sub(r'[「『“‘][ \t]*[」』”’]', '', s)
    s = re.sub(r'[（(][ \t]*[）)]', '', s)
    s = TRAIL_SPACE.sub('', s)
    return s


KANA_ANY = re.compile(r'[぀-ヿｦ-ﾟ]')
LEXICAL = re.compile(r'[぀-ヿｦ-ﾟ㐀-䶿一-鿿]')
HAN = re.compile(r'[㐀-䶿一-鿿]')


def needs_review(cn, jp):
    """规范化后仍需人工/语境判断的判据。返回原因串或 None。"""
    if not cn:
        return 'empty'
    lexical = bool(LEXICAL.search(jp or ''))
    if KANA_ANY.search(cn):
        return 'kana-residue'
    kana_jp = bool(KANA_ANY.search(jp or ''))
    if kana_jp and cn == jp:
        return 'untranslated'
    if lexical and not HAN.search(cn):
        return 'no-han'
    if lexical and len(cn) > 2.2 * max(len(jp), 1) + 12:
        return 'bloated'
    if lexical and len(cn) * 2.6 < len(jp) - 4:
        return 'truncated'
    return None


