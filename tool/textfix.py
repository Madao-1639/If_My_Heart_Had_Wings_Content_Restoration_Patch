"""中文译文的机械规范化（去批注 / 去假名残留 / 统一译名 / 繁转简）。

这些规则是"零判断"的批量改写，故放在流水线里每次构建都执行；需要语境判断的
缺陷（残留假名是术语还是整句未译、漏译补译、语义错译）不在本模块处理，由
script/corpus/build_fan_translations.py 的 REVIEW_FIXES 覆盖表承担。

规则依据（实测与统计见 doc/script-text-extraction.md §3.3）：
  - 羽翼语料里混有译校工作批注（【润色：…】等），必须在入库前剔除；
  - 民汉表对"引擎注音语法 {正文:读音}"按原样保留，读音是日文，必须剥掉；
  - 同一日文术语存在多个中文变体（蝶羽/扬羽、晨阵风云/阵晨风云、机库/车库…），
    取语料内多数形式统一（多数原则由 tmp/term_auto.py 的差分 n-gram 富集度给出）；
  - 繁体字形用 Windows LCMapStringW(2052, LCMAP_SIMPLIFIED_CHINESE) 逐字转换，
    再补 LCMap 不覆盖的日式汉字（荘/﨑/𣘺…）。
"""
import re
import unicodedata
from ctypes import create_unicode_buffer, windll

LCMAP_SIMPLIFIED_CHINESE = 0x02000000
LOCALE_CHS = 2052


def to_simplified(s):
    """整串简体化（Microsoft 权威映射，逐字安全：只改繁简异形，不改词）。"""
    if not s:
        return s
    n = windll.kernel32.LCMapStringW(LOCALE_CHS, LCMAP_SIMPLIFIED_CHINESE, s, -1, None, 0)
    if n <= 0:
        return s
    buf = create_unicode_buffer(n)
    windll.kernel32.LCMapStringW(LOCALE_CHS, LCMAP_SIMPLIFIED_CHINESE, s, -1, buf, n)
    return buf.value


