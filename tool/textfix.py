_MARKERS_TAIL = re.compile(r'(?:%[KP])+$')


def balance_brackets(cn, jp):
    """修平中文行的落单引号（民汉漏收尾「」，成品会把半个引号画上屏）。

    只处理"该行自身不配对"的少数行；成对但数量与日文不同（把『』并入「」等）
    属译者的引号用法，不动。日文自己就没闭合的 5 行按日文同样留空。
    """
    op, cl = cn.count('「'), cn.count('」')
    if op == cl:
        return cn
    if jp.count('「') != jp.count('」'):
        return cn
    if op > cl:
        if not (jp.count('「') or jp.count('」')):
            # 日文是无引号的旁白，中文多出的开引号是民汉手误
            return cn.replace('「', '', op - cl)
        m = _MARKERS_TAIL.search(cn)
        at = m.start() if m else len(cn)
        return cn[:at] + '」' * (op - cl) + cn[at:]
    first = min(cn.find('「'), cn.find('」')) if '「' in cn else cn.find('」')
    if cn[first] == '」':
        return '「' * (cl - op) + cn
    return cn.replace('」', '', cl - op)


TERMINATOR_RE = re.compile(r'(%K|%P)+$')

# 行尾空软换行：\n 之后只剩收尾引号/标点和引擎标记，正文已经结束。
# 多为批注（【注：…】）删除后遗留，上屏是一行只挂着半个收尾引号。
DANGLING_BREAK = re.compile(
    r'\\n[　\s]*(?=[」』’”）)。，、！？…~～]*(?:%[KP])*$)')


def drop_dangling_break(jp, cn):
    """中文比日文多出换行时，删掉行尾那个不承载正文的换行。"""
    if jp.count('\\n') >= cn.count('\\n'):
        return cn
    return DANGLING_BREAK.sub(lambda m: '', cn)


def align_terminator(jp, cn):
    """令中文行的行尾 %K/%P 组合与日文严格一致（民汉表把 %K 行按 %K%P 收录）。"""
    tj = TERMINATOR_RE.search(jp)
    if not tj:
        return cn
    tc = TERMINATOR_RE.search(cn)
    if tc and tc.group(0) == tj.group(0):
        return cn
    body = cn[:tc.start()] if tc else cn
    return body + tj.group(0)


def emit(jp, raw, fixed=None, stat=None):
    """出包口径（构建器与只读复检共用，避免各自重算而漂移）：
    机械归一 → 语境覆盖 → 行尾空换行清理 → 行尾标记对齐 → 落单引号修平。

    `stat` 传入计数器时记录两处改写各命中多少行。
    """
    cn = normalize(fixed or raw or '')
    cn = drop_dangling_break(jp, cn)
    aligned = align_terminator(jp, cn)
    balanced = balance_brackets(aligned, jp)
    if stat is not None:
        if aligned != cn:
            stat['terminator_aligned'] += 1
        if balanced != aligned:
            stat['bracket_balanced'] += 1
    return balanced
